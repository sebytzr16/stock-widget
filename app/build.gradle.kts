// Release signing comes from keystore.properties (local builds) or SIGNING_* environment
// variables (CI). Without either, release builds come out unsigned. See RELEASING.md.
val keystoreProperties = Properties().apply {
    val file = rootProject.file("keystore.properties")
    if (file.exists()) file.inputStream().use { load(it) }
}

fun signing(key: String, env: String): String? = keystoreProperties.getProperty(key) ?: System.getenv(env)

